// npm run images
// backend/pictures/ ki saari pics -> frontend/public/images/ mein copy karta hai
// aur src/utils/imagesMap.js khud bana deta hai (key = file ka naam bina extension).
//   backend/pictures/profile.jpg  ->  img('profile')  ->  /images/profile.jpg
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, '../../backend/pictures');
const DEST = path.resolve(here, '../public/images');
const MAP = path.resolve(here, '../src/utils/imagesMap.js');
const EXT = /\.(jpe?g|png|webp|gif|svg|avif|ico)$/i;

fs.mkdirSync(DEST, { recursive: true });
fs.mkdirSync(SRC, { recursive: true });

// 1) backend/pictures -> public/images
const fromBackend = fs.readdirSync(SRC).filter((f) => EXT.test(f));
for (const f of fromBackend) fs.copyFileSync(path.join(SRC, f), path.join(DEST, f));

// 2) public/images mein jo bhi hai (pehle se rakhi hui bhi) sab map mein
const all = fs.readdirSync(DEST).filter((f) => EXT.test(f)).sort();
const entries = all.map((f) => {
  const key = f.replace(EXT, '').replace(/[^a-zA-Z0-9_-]/g, '-');
  return `  '${key}': '/images/${encodeURI(f)}',`;
});

fs.writeFileSync(
  MAP,
  `// AUTO-GENERATED by "npm run images" — haath se edit mat karo.\nexport const IMAGES = {\n${entries.join('\n')}\n};\n`
);

console.log(`✅ ${fromBackend.length} pic(s) backend/pictures se copy hui, ${all.length} total map mein.`);
if (!all.length) console.log('⚠️  backend/pictures/ khali hai — pics wahan daalo aur dobara chalao.');
